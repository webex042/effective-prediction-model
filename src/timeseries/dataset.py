"""
EPM Time Series Telemetry Dataset & Windowing
=============================================

Generates synthetic multivariate industrial sensor telemetry and creates
leakage-free chronological sliding windows for time-series forecasting.

SENSOR CHANNELS (INDUSTRIAL SPECIFICATION)
------------------------------------------
1. Temperature (°C) : Thermal inertia, ambient drift, friction degradation
2. Vibration (mm/s) : Harmonic machine rotation, high-frequency spikes
3. Pressure (bar)   : Hydraulic cycle oscillations
4. RPM (rev/min)    : Motor shaft rotational velocity
5. Load (%)         : Dynamic factory operational load

TEMPORAL VALIDATION RULE (AVOIDING LOOKAHEAD LEAKAGE)
-----------------------------------------------------
Standard cross-validation and random train/test shuffling violate temporal ordering.
In time series:
  - Training set   : [0, T_train]
  - Validation set : (T_train, T_val]
  - Testing set    : (T_val, T_test]
Future data must NEVER be accessible during training or scaler fitting.
"""

from __future__ import annotations

from typing import Tuple, List, Optional
import numpy as np
import pandas as pd


def generate_multivariate_sensor_telemetry(
    n_timesteps: int = 2000,
    sampling_rate_minutes: int = 10,
    random_seed: int = 42,
) -> Tuple[pd.DataFrame, List[str]]:
    """
    Simulate realistic multivariate industrial sensor telemetry over time.

    Incorporates:
      - Daily thermal & operational cycles
      - Sensor cross-correlations (high load -> higher RPM and thermal rise)
      - Gradual physical degradation in the final third of the timeline
      - Random measurement noise and intermittent hydraulic pressure fluctuations
    """
    rng = np.random.default_rng(random_seed)
    t = np.arange(n_timesteps)

    # 1. Operational Load (%): fluctuates with daily work shifts (period = 24h = 144 steps at 10 min)
    daily_cycle = 24 * (60 // sampling_rate_minutes)
    base_load = 50.0 + 25.0 * np.sin(2 * np.pi * t / daily_cycle)
    load = np.clip(base_load + rng.normal(0, 5.0, n_timesteps), 10.0, 100.0)

    # 2. Motor RPM: proportional to load with rotational inertia
    base_rpm = 1800.0 + 10.0 * load
    rpm = np.clip(base_rpm + rng.normal(0, 20.0, n_timesteps), 1200.0, 3200.0)

    # 3. Hydraulic Pressure (bar): periodic oscillations
    base_pressure = 50.0 + 5.0 * np.cos(4 * np.pi * t / daily_cycle)
    pressure = base_pressure + rng.normal(0, 1.5, n_timesteps)

    # 4. Vibration (mm/s): baseline mechanical vibration + wear degradation
    base_vibration = 1.2 + 0.01 * (load / 10.0) ** 2
    vibration_noise = rng.exponential(0.3, n_timesteps)

    # 5. Core Temperature (°C): thermal lag behind load + friction heating
    # Thermal inertia: temperature is an autoregressive integration of load
    temperature = np.zeros(n_timesteps)
    temperature[0] = 45.0
    ambient = 22.0 + 5.0 * np.sin(2 * np.pi * t / daily_cycle)

    for i in range(1, n_timesteps):
        # Thermal dissipation towards ambient + heat generated by load & rpm
        heat_in = 0.08 * (load[i] / 100.0) * (rpm[i] / 1800.0) * 15.0
        heat_out = 0.03 * (temperature[i - 1] - ambient[i])
        temperature[i] = temperature[i - 1] + heat_in - heat_out + rng.normal(0, 0.2)

    # Physical wear / degradation phase in final 25% of timeline
    degrade_start = int(0.75 * n_timesteps)
    degrade_steps = n_timesteps - degrade_start
    wear_ramp = np.linspace(0.0, 1.0, degrade_steps) ** 2  # Exponential degradation

    # Vibration surges exponentially during bearing failure
    base_vibration[degrade_start:] += 3.5 * wear_ramp
    # Temperature drifts upwards due to bearing friction
    temperature[degrade_start:] += 22.0 * wear_ramp
    # Hydraulic pressure degrades
    pressure[degrade_start:] -= 8.0 * wear_ramp

    vibration = np.clip(base_vibration + vibration_noise, 0.5, 12.0)

    df = pd.DataFrame({
        "temperature": temperature,
        "vibration": vibration,
        "pressure": pressure,
        "rpm": rpm,
        "load": load,
    })

    feature_names = ["temperature", "vibration", "pressure", "rpm", "load"]
    return df, feature_names


def create_sliding_windows(
    data: np.ndarray,
    window_size: int = 24,
    horizon: int = 1,
    stride: int = 1,
    target_channel: int = 0,
) -> Tuple[np.ndarray, np.ndarray]:
    """
    Extract sliding sequence windows for time-series forecasting.

    Parameters
    ----------
    data : np.ndarray of shape (T, D)
        Multivariate time-series data.
    window_size : int, default=24
        Number of historical timesteps lookback (W).
    horizon : int, default=1
        Number of future timesteps to forecast (H).
    stride : int, default=1
        Step size between successive windows.
    target_channel : int, default=0
        Index of the variable to forecast (0 = temperature).

    Returns
    -------
    X : np.ndarray of shape (N_windows, window_size, D)
        Historical input windows.
    y : np.ndarray of shape (N_windows, horizon)
        Future targets.
    """
    T, D = data.shape
    num_windows = (T - window_size - horizon) // stride + 1

    if num_windows <= 0:
        raise ValueError(
            f"Not enough timesteps ({T}) for window_size={window_size} and horizon={horizon}."
        )

    X = np.zeros((num_windows, window_size, D), dtype=np.float32)
    y = np.zeros((num_windows, horizon), dtype=np.float32)

    for i in range(num_windows):
        start = i * stride
        end = start + window_size
        X[i] = data[start:end]
        y[i] = data[end : end + horizon, target_channel]

    return X, y


def temporal_train_test_split(
    X: np.ndarray,
    y: np.ndarray,
    train_ratio: float = 0.7,
    val_ratio: float = 0.15,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """
    Split time series chronologically without shuffling to prevent lookahead leakage.
    """
    n_samples = len(X)
    train_end = int(train_ratio * n_samples)
    val_end = int((train_ratio + val_ratio) * n_samples)

    X_train, y_train = X[:train_end], y[:train_end]
    X_val, y_val = X[train_end:val_end], y[train_end:val_end]
    X_test, y_test = X[val_end:], y[val_end:]

    return X_train, y_train, X_val, y_val, X_test, y_test
